  type Dim = Extract<Entity, { type: 'dimension' }>;
  type DimInfo = { id: string; kind: string; from: number[]; to: number[]; value: number; text: string; anchors: unknown };
  const dims = () => Object.values(doc().levelData[gallery].entities).filter((e): e is Dim => e.type === 'dimension');
  const dimById = (id: string) => dims().find((d) => d.id === id)!;
  const dimInfos = () => smoke.run<DimInfo[]>('plan.dimensions', { levelId: gallery }, { projectId: towerId });
  const labels = () => Object.values(doc().levelData[gallery].entities).filter((e): e is Extract<Entity, { type: 'label' }> => e.type === 'label');
  await focusCanvas();
  await smoke.key('L');
  smoke.check('L picks the dimension tool with its kinds', (await smoke.until(async () => (await attr(smoke, 'tool')) === 'dimension')) && (await smoke.waitFor(`${tab} [data-testid=dimension-kind]`)));
  await wait(100);
  rect = (await smoke.rect(canvas))!;
